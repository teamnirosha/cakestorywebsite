export function toMarathiDigits(num: number | string): string {
  const marathiDigits = ["०", "१", "२", "३", "४", "५", "६", "७", "८", "९"];
  return String(num).replace(/[0-9]/g, (d) => marathiDigits[Number(d)]);
}

